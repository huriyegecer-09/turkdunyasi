#!/usr/bin/env python3
"""Extract HTTP(S) PDF link annotations as page-relative Flip link data.

The PDF page number is kept separately from the Flip page number so an export
that inserts or removes a cover can be handled with --page-offset.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Any

from pypdf import PdfReader


def dereference(value: Any) -> Any:
    return value.get_object() if hasattr(value, "get_object") else value


def extract_links(pdf_path: Path, page_offset: int) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    reader = PdfReader(str(pdf_path))
    links: list[dict[str, Any]] = []
    page_sizes: list[tuple[float, float]] = []

    for pdf_page, page in enumerate(reader.pages, start=1):
        media_box = page.mediabox
        width = float(media_box.width)
        height = float(media_box.height)
        page_sizes.append((width, height))

        annots = dereference(page.get("/Annots")) or []
        for annot_ref in annots:
            annot = dereference(annot_ref)
            action = dereference(annot.get("/A")) if annot else None
            uri = action.get("/URI") if action else None
            if not uri:
                continue
            href = str(uri)
            if not href.lower().startswith(("http://", "https://")):
                continue

            rect = annot.get("/Rect")
            if not rect or len(rect) != 4:
                continue
            x1, y1, x2, y2 = (float(value) for value in rect)
            left, right = min(x1, x2), max(x1, x2)
            bottom, top = min(y1, y2), max(y1, y2)
            links.append(
                {
                    "pdfPage": pdf_page,
                    "href": href,
                    "leftPct": round(left / width * 100, 6),
                    "topPct": round((height - top) / height * 100, 6),
                    "widthPct": round((right - left) / width * 100, 6),
                    "heightPct": round((top - bottom) / height * 100, 6),
                }
            )

    common_width, common_height = Counter(page_sizes).most_common(1)[0][0]
    config = {
        "pdfPageCount": len(reader.pages),
        "pageOffset": page_offset,
        "pdfPageWidth": common_width,
        "pdfPageHeight": common_height,
        "pdfPageSizeVariants": len(set(page_sizes)),
        "annotationCount": len(links),
    }
    return config, links


def write_outputs(config: dict[str, Any], links: list[dict[str, Any]], output_js: Path, output_json: Path) -> None:
    output_js.parent.mkdir(parents=True, exist_ok=True)
    output_json.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(links, ensure_ascii=False, indent=2)
    output_json.write_text(payload + "\n", encoding="utf-8")
    js = (
        "// Generated by patch/extract-pdf-links.py; do not edit by hand.\n"
        f"window.FLIP_PDF_LINK_CONFIG = {json.dumps(config, ensure_ascii=False, indent=2)};\n"
        f"window.FLIP_PDF_LINKS = {payload};\n"
    )
    output_js.write_text(js, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pdf", type=Path, help="Source PDF containing link annotations")
    parser.add_argument("--page-offset", type=int, default=0, help="Flip page = PDF page + offset")
    parser.add_argument("--output-js", type=Path, required=True)
    parser.add_argument("--output-json", type=Path, required=True)
    args = parser.parse_args()

    config, links = extract_links(args.pdf, args.page_offset)
    write_outputs(config, links, args.output_js, args.output_json)
    print(f"Extracted {len(links)} HTTP(S) links from {config['pdfPageCount']} PDF pages.")
    print(f"Page mapping: Flip page = PDF page + {args.page_offset}.")


if __name__ == "__main__":
    main()
